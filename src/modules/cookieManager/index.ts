/**
 * cookieManager/index.ts
 *
 * Core cookie CRUD + single-site I/O (JSON / Netscape).
 *
 * Work-order coverage:
 *   Delta — CRUD integrity: delete/update build valid URLs for dot-prefixed
 *           domains; update preserves SameSite and storeId invariants;
 *           import is failure-isolated via Promise.allSettled with fallback
 *           normalization (strip leading dot / omit unsupported SameSite).
 *   Gamma  — URL synthesis: leading dots stripped, protocol derived from the
 *           cookie's own `secure` flag (and promoted to https:// for
 *           SameSite=None, __Secure-*, and __Host-*), path slash-normalized.
 */

/** SameSite string union ("no_restriction" | "lax" | "strict" | "unspecified"). */
type SameSite = `${chrome.cookies.SameSiteStatus}`;

export interface Cookie {
  name: string;
  value: string;
  domain: string;
  path: string;
  secure: boolean;
  httpOnly: boolean;
  expirationDate?: number;
  hostOnly?: boolean;
  session?: boolean;
  sameSite?: SameSite;
  storeId?: string;
}

export interface ImportResult {
  imported: number;
  failed: number;
}

const normalizePath = (rawPath?: string): string => {
  if (!rawPath) return '/';
  return rawPath.startsWith('/') ? rawPath : `/${rawPath}`;
};

const isSingleLabelOrIp = (bareHost: string): boolean => {
  if (!bareHost) return true;
  if (bareHost === 'localhost' || !bareHost.includes('.')) return true;
  if (/^\d{1,3}(?:\.\d{1,3}){3}$/.test(bareHost)) return true;
  if (bareHost.startsWith('[') || bareHost.includes(':')) return true;
  return false;
};

/** Gamma-compliant URL synthesis for cookies. */
const cookieUrl = (cookie: Cookie): string => {
  const host = (cookie.domain || '').replace(/^\.+/, '');
  const isHostPrefix = typeof cookie.name === 'string' && cookie.name.startsWith('__Host-');
  const isSecurePrefix = typeof cookie.name === 'string' && cookie.name.startsWith('__Secure-');
  const path = isHostPrefix ? '/' : normalizePath(cookie.path);
  const secure =
    Boolean(cookie.secure) ||
    cookie.sameSite === 'no_restriction' ||
    isHostPrefix ||
    isSecurePrefix;
  return `${secure ? 'https' : 'http'}://${host}${path}`;
};

export class CookieManagerModule {
  static async getCookiesForCurrentTab(): Promise<Cookie[]> {
    try {
      const [tab] = await chrome.tabs.query({ active: true, currentWindow: true });
      if (tab?.url) {
        const url = new URL(tab.url);
        return await chrome.cookies.getAll({ domain: url.hostname });
      }
      return [];
    } catch (error) {
      console.error('Error getting cookies:', error);
      return [];
    }
  }

  static async deleteCookie(cookie: Cookie): Promise<boolean> {
    try {
      const details: chrome.cookies.CookieDetails = {
        url: cookieUrl(cookie),
        name: cookie.name,
      };
      if (cookie.storeId) details.storeId = cookie.storeId;
      const removed = await chrome.cookies.remove(details);
      return removed !== null;
    } catch (error) {
      console.error('Error deleting cookie:', error);
      return false;
    }
  }

  static async clearAllCookiesForSite(): Promise<ImportResult> {
    try {
      const cookies = await this.getCookiesForCurrentTab();
      const results = await Promise.allSettled(
        cookies.map((cookie) => this.deleteCookie(cookie)),
      );
      let removed = 0;
      let failed = 0;
      for (const result of results) {
        if (result.status === 'fulfilled' && result.value) removed++;
        else failed++;
      }
      return { imported: removed, failed };
    } catch (error) {
      console.error('Error clearing cookies:', error);
      return { imported: 0, failed: 0 };
    }
  }

  /* ── Single-site export ── */

  static exportCookies(cookies: Cookie[], hostname?: string): void {
    const site = hostname ? `${hostname}_` : '';
    const dataStr = JSON.stringify(cookies, null, 2);
    const dataUri =
      'data:application/json;charset=utf-8,' + encodeURIComponent(dataStr);

    const exportFileDefaultName =
      `cookies_${site}${new Date().toISOString().split('T')[0]}.json`;

    if (
      typeof chrome !== 'undefined' &&
      chrome.downloads &&
      typeof chrome.downloads.download === 'function'
    ) {
      try {
        chrome.downloads.download({
          url: dataUri,
          filename: exportFileDefaultName,
        });
        return;
      } catch {
        // Fall through to anchor download
      }
    }

    const linkElement = document.createElement('a');
    linkElement.setAttribute('href', dataUri);
    linkElement.setAttribute('download', exportFileDefaultName);
    linkElement.click();
  }

  /**
   * Netscape HTTP Cookie File serialization. HttpOnly cookies carry the
   * `#HttpOnly_` domain prefix so exports round-trip losslessly.
   */
  static toNetscape(cookies: Cookie[]): string {
    let header = '# Netscape HTTP Cookie File\n';
    header += '# Generated by 4ndr0cookie\n';
    header += '# This file contains the HTTP cookies for a single site\n\n';

    const lines = cookies.map((cookie) => {
      const isSubdomainCookie =
        cookie.hostOnly === true
          ? false
          : cookie.hostOnly === false
            ? true
            : cookie.domain.startsWith('.');
      const bareDomain = cookie.domain.replace(/^\.+/, '');
      const domain = isSubdomainCookie ? `.${bareDomain}` : bareDomain;
      const subdomainFlag = isSubdomainCookie ? 'TRUE' : 'FALSE';
      const path = normalizePath(cookie.path);
      const secureFlag = cookie.secure ? 'TRUE' : 'FALSE';
      const expiration =
        cookie.expirationDate && !cookie.session
          ? Math.floor(cookie.expirationDate)
          : '0';
      const prefix = cookie.httpOnly ? '#HttpOnly_' : '';

      return `${prefix}${domain}\t${subdomainFlag}\t${path}\t${secureFlag}\t${expiration}\t${cookie.name}\t${cookie.value}`;
    });

    return header + lines.join('\n') + (lines.length ? '\n' : '');
  }

  static exportNetscape(cookies: Cookie[], hostname?: string): void {
    const site = hostname ? `${hostname}_` : '';
    const content = this.toNetscape(cookies);
    const dataUri = 'data:text/plain;charset=utf-8,' + encodeURIComponent(content);
    const exportFileName =
      `cookies_${site}${new Date().toISOString().split('T')[0]}.txt`;

    if (
      typeof chrome !== 'undefined' &&
      chrome.downloads &&
      typeof chrome.downloads.download === 'function'
    ) {
      try {
        chrome.downloads.download({
          url: dataUri,
          filename: exportFileName,
        });
        return;
      } catch {
        // Fall through to anchor download
      }
    }

    const linkElement = document.createElement('a');
    linkElement.setAttribute('href', dataUri);
    linkElement.setAttribute('download', exportFileName);
    linkElement.click();
  }

  /**
   * Netscape parser (Delta). Handles `#HttpOnly_` prefixed lines, comment
   * lines, blank lines, session cookies (expiry <= 0) and the include-
   * subdomains flag mapped onto domain / hostOnly semantics.
   */
  static parseNetscape(text: string): Cookie[] {
    const cookies: Cookie[] = [];
    const lines = text.split(/\r?\n/);

    for (const rawLine of lines) {
      const line = rawLine.trim();
      if (!line) continue;
      // Comments — but #HttpOnly_ prefixed rows are real cookies
      if (line.startsWith('#') && !line.startsWith('#HttpOnly_')) continue;

      const match =
        /^#HttpOnly_([^\t]+)\t(TRUE|FALSE)\t([^\t]*)\t(TRUE|FALSE)\t(-?\d+)\t([^\t]*)\t(.*)$/.exec(
          line,
        ) ??
        /^([^\t#][^\t]*)\t(TRUE|FALSE)\t([^\t]*)\t(TRUE|FALSE)\t(-?\d+)\t([^\t]*)\t(.*)$/.exec(
          line,
        );
      if (!match) continue;

      const [, rawDomain, subdomainFlag, path, secureFlag, expiration, name, value] =
        match;
      if (!name) continue;

      let domain = rawDomain;
      let hostOnly = false;
      if (subdomainFlag === 'TRUE') {
        // Domain cookie — ensure leading dot so subdomains match
        if (!domain.startsWith('.')) domain = '.' + domain;
      } else {
        // Host-only cookie — strip any leading dot
        domain = domain.replace(/^\.+/, '');
        hostOnly = true;
      }

      const expiryNumber = parseInt(expiration, 10);
      const isSession = !Number.isFinite(expiryNumber) || expiryNumber <= 0;

      cookies.push({
        name,
        value,
        domain,
        path: normalizePath(path),
        secure: secureFlag === 'TRUE',
        httpOnly: line.startsWith('#HttpOnly_'),
        hostOnly,
        session: isSession,
        ...(isSession ? {} : { expirationDate: expiryNumber }),
      });
    }

    return cookies;
  }

  /**
   * Auto-detecting import: accepts raw JSON arrays, `{ cookies: [...] }`
   * wrappers, and Netscape cookie files.
   */
  static parseImport(text: string): Cookie[] {
    const trimmed = text.trim();
    if (trimmed.startsWith('[') || trimmed.startsWith('{')) {
      const parsed = JSON.parse(trimmed);
      if (Array.isArray(parsed)) return parsed as Cookie[];
      if (parsed && Array.isArray((parsed as { cookies?: Cookie[] }).cookies)) {
        return (parsed as { cookies: Cookie[] }).cookies;
      }
      throw new Error('JSON does not contain a cookie array.');
    }
    return this.parseNetscape(trimmed);
  }

  /* ── Import / update ── */

  static async importCookies(cookiesData: Cookie[]): Promise<ImportResult> {
    try {
      if (!Array.isArray(cookiesData) || cookiesData.length === 0) {
        return { imported: 0, failed: 0 };
      }

      const storeIds = await chrome.cookies.getAllCookieStores().then((stores) =>
        stores.map((s) => s.id),
      );

      const setOne = async (cookie: Cookie): Promise<boolean> => {
        const isHostPrefix = typeof cookie.name === 'string' && cookie.name.startsWith('__Host-');
        const isSecurePrefix = typeof cookie.name === 'string' && cookie.name.startsWith('__Secure-');
        const bareHost = (cookie.domain || '').replace(/^\.+/, '');
        const effectivePath = isHostPrefix ? '/' : normalizePath(cookie.path);
        const effectiveSecure =
          Boolean(cookie.secure) ||
          cookie.sameSite === 'no_restriction' ||
          isHostPrefix ||
          isSecurePrefix;

        const details: chrome.cookies.SetDetails = {
          url: `${effectiveSecure ? 'https' : 'http'}://${bareHost}${effectivePath}`,
          name: cookie.name,
          value: cookie.value,
          path: effectivePath,
          secure: effectiveSecure,
          httpOnly: Boolean(cookie.httpOnly),
        };
        if (!isHostPrefix && !cookie.hostOnly && cookie.domain && !isSingleLabelOrIp(bareHost)) {
          details.domain = cookie.domain;
        }
        if (cookie.expirationDate && !cookie.session) {
          details.expirationDate = cookie.expirationDate;
        }
        if (
          cookie.sameSite === 'no_restriction' ||
          cookie.sameSite === 'lax' ||
          cookie.sameSite === 'strict' ||
          cookie.sameSite === 'unspecified'
        ) {
          if (cookie.sameSite === 'no_restriction') {
            details.secure = true;
            details.url = `https://${bareHost}${effectivePath}`;
          }
          details.sameSite = cookie.sameSite;
        }
        if (cookie.storeId && storeIds.includes(cookie.storeId)) {
          details.storeId = cookie.storeId;
        }

        try {
          const result = await chrome.cookies.set(details);
          if (result !== null) return true;
        } catch {
          // If the cookie did not fail intentionally and has fallback-eligible attributes, try fallback only when domain/sameSite rejection occurred
        }

        if (
          cookie.sameSite === 'unspecified' ||
          (cookie.sameSite === 'no_restriction' && !cookie.secure) ||
          (details.domain && details.domain.startsWith('.'))
        ) {
          const fallbackDetails: chrome.cookies.SetDetails = {
            url: `${Boolean(cookie.secure) || isHostPrefix || isSecurePrefix ? 'https' : 'http'}://${bareHost}${effectivePath}`,
            name: cookie.name,
            value: cookie.value,
            path: effectivePath,
            secure: Boolean(cookie.secure) || isHostPrefix || isSecurePrefix,
            httpOnly: Boolean(cookie.httpOnly),
            ...(!isHostPrefix && !cookie.hostOnly && bareHost && !isSingleLabelOrIp(bareHost)
              ? { domain: bareHost }
              : {}),
            ...(cookie.expirationDate && !cookie.session
              ? { expirationDate: cookie.expirationDate }
              : {}),
            ...(cookie.sameSite &&
            cookie.sameSite !== 'no_restriction' &&
            cookie.sameSite !== 'unspecified'
              ? { sameSite: cookie.sameSite }
              : {}),
            ...(cookie.storeId && storeIds.includes(cookie.storeId)
              ? { storeId: cookie.storeId }
              : {}),
          };
          try {
            const fallbackResult = await chrome.cookies.set(fallbackDetails);
            return fallbackResult !== null;
          } catch {
            return false;
          }
        }

        return false;
      };

      // Gamma: a single rejected write must not terminate the sequence
      const results = await Promise.allSettled(cookiesData.map(setOne));
      let imported = 0;
      let failed = 0;
      for (const result of results) {
        if (result.status === 'fulfilled' && result.value) imported++;
        else failed++;
      }
      return { imported, failed };
    } catch (error) {
      console.error('Error importing cookies:', error);
      return { imported: 0, failed: cookiesData.length };
    }
  }

  /**
   * Inline edit (Delta). Sets the patched cookie first; only if the identity
   * key (name) changed is the original removed afterwards, so a failed write
   * can never destroy the original cookie. Preserves SameSite and validates storeId.
   */
  static async updateCookie(
    original: Cookie,
    patch: { name: string; value: string },
  ): Promise<boolean> {
    try {
      const nextName = patch.name.trim();
      if (!nextName) return false;

      const storeIds = await chrome.cookies
        .getAllCookieStores()
        .then((stores) => stores.map((s) => s.id))
        .catch(() => [] as string[]);

      const isHostPrefix = nextName.startsWith('__Host-');
      const isSecurePrefix = nextName.startsWith('__Secure-');
      const bareHost = (original.domain || '').replace(/^\.+/, '');
      const effectivePath = isHostPrefix ? '/' : normalizePath(original.path);
      const effectiveSecure =
        Boolean(original.secure) ||
        original.sameSite === 'no_restriction' ||
        isHostPrefix ||
        isSecurePrefix;

      const details: chrome.cookies.SetDetails = {
        url: `${effectiveSecure ? 'https' : 'http'}://${bareHost}${effectivePath}`,
        name: nextName,
        value: patch.value,
        path: effectivePath,
        secure: effectiveSecure,
        httpOnly: Boolean(original.httpOnly),
      };
      if (!isHostPrefix && !original.hostOnly && original.domain && !isSingleLabelOrIp(bareHost)) {
        details.domain = original.domain;
      }
      if (original.expirationDate && !original.session) {
        details.expirationDate = original.expirationDate;
      }
      if (
        original.sameSite === 'no_restriction' ||
        original.sameSite === 'lax' ||
        original.sameSite === 'strict' ||
        original.sameSite === 'unspecified'
      ) {
        if (original.sameSite === 'no_restriction') {
          details.secure = true;
          details.url = `https://${bareHost}${effectivePath}`;
        }
        details.sameSite = original.sameSite;
      }
      if (
        original.storeId &&
        (storeIds.length === 0 || storeIds.includes(original.storeId))
      ) {
        details.storeId = original.storeId;
      }

      const set = await chrome.cookies.set(details);
      if (!set) return false;

      if (nextName !== original.name) {
        await this.deleteCookie(original);
      }
      return true;
    } catch (error) {
      console.error('Error updating cookie:', error);
      return false;
    }
  }
}
